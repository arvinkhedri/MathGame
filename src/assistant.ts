/* ---------- رد موضوع‌های خارج از بحث ---------- */
const OFFTOPIC = /فوتبال|هوا(ی)? امروز|غذا|ناهار|شام|عشقه?|دوستدختر|خرید|گوشی|فیلم|آواز|ترانه|سیاست|شغل|برنامه نویسی|برنامه‌نویسی|دانشکده|کنکور|گیم|بازیکن/;

/* ---------- مغز محلی ---------- */
function brain(raw: string): string {
  const t = norm(raw);

  // ۱) لو ندادن پاسخ سؤالِ در حال بازی
  if (/(جواب|حل|پاسخ)/.test(t) && /(بازی|در حال|همین الان|همین سوال|سوال بازی)/.test(t)) {
    return "پاسخ سؤالاتِ داخل بازی را لو نمی‌دهم؛ این‌طوری رکوردت واقعی می‌شود! اما می‌توانم روشِ حلِ هر مبحث را مرحله‌به‌مرحله یاد بدهم تا خودت جواب را بیابی. کدام مبحث؟ (اول و مرکب، گویا و گنگ، غربال، تلسکوپی، مسلسل)";
  }

  // ۲) «نشان بده» — آشکارسازی پاسخِ راهنماییِ قبلی
  const revealAsk = /(نشان بده|نشان بده|جواب کامل|جواب نهایی|بگو جواب|answer)/.test(t);
  if (revealAsk && lastCtx) {
    if (lastCtx.kind.startsWith("prime:") && lastCtx.n) {
      const n = lastCtx.n;
      if (isPrimeOf(n)) {
        const limit = Math.floor(Math.sqrt(n));
        return `بررسی کامل: از 2 تا ${limit} (= ⌊√${n}⌋) هیچ‌کدام ${n} را نمی‌شود بخشوند؛ پس ${n} فقط دو مقسوم‌علیه دارد (۱ و خودش) و اول است.`;
      }
      const f = factorOf(n)!;
      return `بررسی کامل: ${n} = ${f[0]} × ${f[1]} ، پس ${n} مرکب است و فاکتورهای اولش ${f[0]} و ${f[1]} (و...) هستند.`;
    }
    if (lastCtx.kind.startsWith("sqrt:") && lastCtx.n) {
      const n = lastCtx.n;
      const r = Math.round(Math.sqrt(n));
      return r * r === n
        ? `√${n} = ${r} ، یک عدد صحیح است؛ پس گویاست (چون ${r} = ${r}/1).`
        : `√${n} گنگ است: اگر گویا بود، √${n} = k/n و از آن ${n}n² = k² درمی‌آمد؛ اما ${n} مربع کامل نیست، پس چنین k و n‌ای وجود ندارد.`;
    }
  }

  // ۳) «N اول است؟» / «N مرکب است؟»
  const pm = t.match(/(\d{1,4})\s*(اول|مرکب)/);
  if (pm && t.length < 60) {
    const n = Number(pm[1]);
    const kind = pm[2];
    lastCtx = { kind: `prime:${n}`, n };
    if (kind === "مرکب") {
      const f = factorOf(n);
      return `برای بررسی ${n}: اگر مقسوم‌علیه‌ای غیر از ۱ و خودش پیدا کنی، مرکب است. از ۲ شروع کن: ${
        f
          ? `${n} = ${f[0]} × ${f[1]} ، پس ${n} مرکب است.`
          : n < 2
            ? "دقت کن: برای مرکب بودن باید بزرگ‌تر از ۱ باشد. عدد ۱ نه اول است و نه مرکب."
            : `تا √${n} ≈ ${Math.floor(Math.sqrt(n))} هیچ مقسوم‌علیه‌ای ندارد؛ پس ${n} اول است (مرکب نیست).`
      }`;
    }
    const limit = Math.floor(Math.sqrt(n));
    const cand = limit - 1;
    if (n < 2) return "دقت کن: عددهای اول از ۲ به بعد هستند؛ ۱ نه اول است و نه مرکب. عدد بزرگ‌تری بفرست تا با هم غربالش کنیم.";
    return [
      `برای فهمیدن «اول» بودنِ ${n}، فقط کافی است بخش‌پذیری‌اش را تا √${n} ≈ ${limit} بررسی کنیم؛ یعنی ${Math.max(1, cand)} کاندیدا (2 تا ${limit}).`,
      n % 2 === 0 ? `نکته‌ی شروع: ${n} زوج است — همین‌جا یک جواب بزرگ داری!` : "نکته‌ی شروع: زوج نیست، پس ۲ را رد کن و از ۳ برو به ۵، ۷ و …",
      "اگر در آخر هیچ‌کدام نخورد، اول است. اگر خواستی نتیجه را هم ببینی، بگو «نشان بده».",
    ].join("\n");
  }

  // ۴) «√N گویاست یا گنگ؟»
  const sm = t.match(/(sqrt|rish|ریشه|رادیکال|√).*?(\d{1,4})/);
  if (sm) {
    const n = Number(sm[2]);
    lastCtx = { kind: `sqrt:${n}`, n };
    const r = Math.floor(Math.sqrt(n) + 1e-9);
    return [
      `برای √${n} کلیدِ کار این است: آیا ${n} مربع کامل است؟`,
      r * r === n
        ? `بله: ${r} × ${r} = ${n} ، پس √${n} = ${r} یک عدد صحیح است — بنابراین گویاست.`
        : `نه: ${r * r} < ${n} < ${(r + 1) * (r + 1)} ، یعنی ${n} بین دو مربع کامل است. وقتی زیررادیکال مربع کامل نباشد، ریشه‌اش گنگ است؛ پس √${n} گنگ است.`,
      "اگر خواستی دلیل دقیق‌ترش را ببینی، بگو «نشان بده».",
    ].join("\n");
  }

  // ۵) محاسبه‌ی کسر مسلسل [a ; b , c]
  const cf = t.match(/(\d{1,2})\s*[;؛]\s*(\d{1,2})\s*[,،]\s*(\d{1,2})/);
  if (cf && /مسلسل|fraction|[\[[]/.test(t)) {
    const a = Number(cf[1]);
    const b = Number(cf[2]);
    const c = Number(cf[3]);
    lastCtx = { kind: "cf", n: a * 100 + b * 10 + c };
    const num = a * (b * c + 1) + c;
    const den = b * c + 1;
    const g = gcdOf(num, den);
    return [
      `[${a} ; ${b} , ${c}] مرحله‌به‌مرحله:`,
      `از انتها: ${b} + 1/${c} = ${(b * c + 1)}/${c}`,
      `معکوسش: ${c}/(${b * c + 1})`,
      `در انتها: ${a} + ${c}/(${b * c + 1}) = ${num / g}/${den / g}.`,
    ].join("\n");
  }

  // ۶) بلوک‌های دانشی
  for (const k of KNOWLEDGE) {
    if (k.keys.test(t)) {
      lastCtx = null;
      const out = k.text(t);
      return `${out}\n\n---\nاگر سوال دیگری از مباحث بازی داری (اعداد اول و مرکب، گویا و گنگ، غربال، رادیکال، تلسکوپی، مسلسل) بپرس؛ مرحله‌به‌مرحله با هم حل می‌کنیم.`;
    }
  }

  // ۷) 22/7 و 3.14
  if (/22\/7|3\.14/.test(t)) {
    return "خوب پرسیدی: 22/7 یک کسر است (۲۲ بر ۷) و هر کسری از دو عدد صحیح گویاست — حتی اگر نزدیک‌شده‌ی خوبِ π باشد. خودِ π گنگ است و کسر نمی‌شود.";
  }

  // ۸) خارج از موضوع
  if (OFFTOPIC.test(t)) {
    return "من دستیار ریاضیِ این بازی‌ام و بیشتر در این مباحث کمکت می‌کنم: اعداد اول و مرکب، اعداد گویا و گنگ، روش غربال، رادیکال‌ها، کسرهای تلسکوپی و کسرهای مسلسل. سوال ریاضی‌ات را بفرست تا مرحله‌به‌مرحله حلش کنیم!";
  }

  // ۹) مطمئن نیستم
  if (/\d/.test(t) || /ریاضی|حساب|عدد|کسر/.test(t)) {
    lastCtx = null;
    return "راستش را بخوای از این سوال دقیق مطمئن نیستم و دوست ندارم جواب ساختگی بدهم. اگر کمی دقیق‌ترش بنویسی (مثلاً عدد‌ها یا مبحث را مشخص کنی) با هم بررسی می‌کنیم. موضوع‌هایی که خیلی خوب می‌دانم: اعداد اول و مرکب، گویا و گنگ، غربال اراتوستن، رادیکال، تلسکوپی و کسرهای مسلسل.";
  }
  return "سلام! درباره‌ی مباحث بازی می‌توانی بپرسی؛ مثلاً «عدد ۲۹ اول است؟» یا «روش غربال چیست؟» یا «" + SQ2 + " گویاست یا گنگ؟»";
}

function gcdOf(a: number, b: number): number {
  return b === 0 ? a : gcdOf(b, a % b);
}

/* ---------- دروازه‌ی عمومی ----------
   تا زمانی که سرویس/کلید API در دسترس نیست، از brain محلی استفاده
   می‌شود. برای اتصال واقعی، بدنه‌ی این تابع را با fetch به
   واسطِ سمت سرور جایگزین کنید (کلید API هرگز در مرورگر). */
export async function askAssistant(raw: string, cancel: CancelToken): Promise<string> {
  await new Promise((r) => setTimeout(r, 600 + Math.random() * 900));
  if (cancel.cancelled) throw new Error("cancelled");
  return brain(raw);
}

